"""The office format of the generated reports (ASSUMPTIONS 469): the budget in words, the numbered outputs, the period
phrase, "F. Overall Assessment", the default office line and the letterhead on the figures reports."""

from datetime import date
from decimal import Decimal

import pytest

from reports import draft_export, draft_facts
from reports.generator import section_specs
from reports.models import ReportDraft
from reports.money_words import number_in_words, pesos_in_words

pytestmark = pytest.mark.django_db


@pytest.mark.parametrize(("amount", "words"), [
    ("27000.00", "Twenty-Seven Thousand Pesos"),
    ("1", "One Peso"),
    ("0", "Zero Pesos"),
    ("1250.50", "One Thousand Two Hundred Fifty Pesos and 50/100"),
    ("115000", "One Hundred Fifteen Thousand Pesos"),
    ("2000000.005", "Two Million Pesos and 01/100"),  # half-up to centavos
    (Decimal("60120.00"), "Sixty Thousand One Hundred Twenty Pesos"),
])
def test_pesos_in_words(amount, words) -> None:
    assert pesos_in_words(amount) == words


def test_number_in_words_scales() -> None:
    assert number_in_words(1_000_001) == "One Million One"
    assert number_in_words(999) == "Nine Hundred Ninety-Nine"
    with pytest.raises(ValueError):
        number_in_words(-1)


def test_outputs_end_with_semicolons_and_and() -> None:
    assert draft_export.listed_outputs(["Conducted A.", "Conducted B;", "Issued C"]) == [
        "Conducted A;", "Conducted B; and", "Issued C."]
    assert draft_export.listed_outputs(["Only one"]) == ["Only one."]
    assert draft_export.listed_outputs([" ", "."]) == []


def test_period_phrase_names_the_quarter_half_or_year() -> None:
    assert draft_facts.accomplishment_period_phrase(date(2026, 7, 1), date(2026, 9, 30)) == "the third quarter"
    assert draft_facts.accomplishment_period_phrase(date(2026, 1, 1), date(2026, 6, 30)) == "the first half of the year"
    assert draft_facts.accomplishment_period_phrase(date(2026, 7, 1), date(2026, 12, 31)) == "the second half of the year"
    assert draft_facts.accomplishment_period_phrase(date(2026, 1, 1), date(2026, 12, 31)) == "the year"


def test_accomplishment_report_ends_with_the_overall_assessment() -> None:
    keys = [key for key, _label, _how in section_specs(ReportDraft.Kind.ACCOMPLISHMENT_REPORT, {"activities": []})]
    assert keys[-1] == "assessment"
    labels = dict((key, label) for key, label, _how in section_specs(ReportDraft.Kind.ACCOMPLISHMENT_REPORT, {}))
    assert labels["assessment"] == "F. Overall Assessment"


def test_office_line_defaults_to_navigatu(settings) -> None:
    assert draft_export.office_line({}) == settings.LETTERHEAD_OFFICE_LINE
    assert draft_export.office_line({"office_line": "  "}) == settings.LETTERHEAD_OFFICE_LINE
    assert draft_export.office_line({"office_line": settings.LETTERHEAD_VP_OFFICE_LINE}) == settings.LETTERHEAD_VP_OFFICE_LINE


def test_budget_facts_have_the_total_in_words(activity) -> None:
    from activities.models import BudgetCategory, BudgetLine

    category = BudgetCategory.objects.get_or_create(name="Meals/Snacks")[0]
    BudgetLine.objects.create(activity=activity, category=category, particulars="Lunch", quantity=60, unit="pax",
                              days=1, unit_price=Decimal("250.00"), line_total=Decimal("15000.00"), sort_order=1)
    budget = draft_facts._budget(activity)
    assert budget["total_words"] == pesos_in_words(budget["total"].replace("₱", "").replace(",", ""))
    assert budget["note"].startswith("The amounts presented reflect the budget allocation")


def test_no_budget_lines_means_no_words(activity) -> None:
    assert draft_facts._budget(activity)["total_words"] == ""


def test_figures_report_has_the_compact_letterhead() -> None:
    from django.utils import timezone

    from reports import content as report_content
    from reports import metrics, pdf

    content = report_content.build_content("accomplishment", ["summary"],
                                           metrics.ReportFilters(date(2026, 1, 1), date(2026, 3, 31)),
                                           generated_by="Test", generated_at=timezone.now())
    html = pdf.report_html(content)
    assert 'class="lh lh-compact"' in html and "Generated by CSU-TBI Track" in html
    assert "size: A4 landscape" in html


def test_one_participants_evaluation_has_the_full_letterhead(activity) -> None:
    from django.utils import timezone

    from reports import pdf

    data = {"name": "Ana Cruz", "certificate_name": "Ana Cruz", "category": "MSMEs", "submitted_at": timezone.now(),
            "average": None, "ratings": [], "answers": []}
